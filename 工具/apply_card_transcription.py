def main(check_only):
    with io.open(DRAFT, encoding='utf-8') as fh:
        draft = json.load(fh)
    items = draft['items']
    if len(items) != 124:
        raise SystemExit('底稿条目数 %d ≠ 124，先修底稿' % len(items))
    covered = set(TRANSCRIPTION) | BACK_TEMPLATE
    missing = [i for i in range(1, 125) if i not in covered]
    extra = [i for i in TRANSCRIPTION if i in BACK_TEMPLATE]
    if missing or extra:
        raise SystemExit('转录面不齐：未覆盖 %s，越界 %s' % (missing, extra))
    n_visual = n_blank = n_doubt = 0
    for pos, it in enumerate(items, 1):
        if pos in BACK_TEMPLATE:
            continue
        text = TRANSCRIPTION[pos]
        it['bottom_text'] = text
        it['bottom_source'] = '目视转录'
        it['取文方式'] = ('目视转录（模板卡无文案面板）' if text == '' else '目视转录（拼版＋定向复核）')
        it['存疑'] = DOUBTFUL.get(pos, '')
        if pos in FRONT_SUBTITLE:
            it['template_subtitle'] = FRONT_SUBTITLE[pos]
        if text == '':
            n_blank += 1
        else:
            n_visual += 1
        if pos in DOUBTFUL:
            n_doubt += 1
    draft['transcribed_by'] = ('会话代理目视转录，2026-11-08；12 版拼版覆盖 119 张＋3 张定向复核件；'
                               'OCR 只作提示列不作结论')
    print('目视转录有文案 %d 张／模板卡空文案 %d 张／模板背面判空 %d 张（共 124）'
          % (n_visual, n_blank, len(BACK_TEMPLATE)))
    print('存疑 %d 条：%s' % (n_doubt, '、'.join('#%03d' % k for k in DOUBTFUL)))
    if check_only:
        return 0
    with io.open(DRAFT, 'w', encoding='utf-8') as fh:
        json.dump(draft, fh, ensure_ascii=False, indent=1)
    filled = sum(1 for it in json.load(io.open(DRAFT, encoding='utf-8'))['items'] if it['bottom_text'])
    print('回写后非空 bottom_text %d 条' % filled)
    return 0


