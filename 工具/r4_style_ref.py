def send_body(body_text):
    """实际送入串＝前导一行 + 现串正文逐字（正文里已有的换行不动）。"""
    return PREFIX_LINE + "\n" + body_text


def dims(rel):
    from PIL import Image
    p = os.path.join(ROOT, rel.replace("/", os.sep))
    with Image.open(p) as im:
        im.load()
        return "%dx%d" % im.size


def check_pool(pool, why):
    """池内逐枚取到尺寸才算池成立；不在盘或打不开直接停，不留「池子中道崩殂」的半批。"""
    out = []
    for rel in pool:
        p = os.path.join(ROOT, rel.replace("/", os.sep))
        if not os.path.isfile(p):
            raise SystemExit("R4 母图池缺件（%s）：%s" % (why, rel))
        out.append((rel, dims(rel)))
    return out


def assign(pool, idx, size):
    """确定性分配：同画幅子池优先，子池空则整池，按池内轮转取第 idx 枚。

    为什么用序号而不是按 id 哈希：哈希分配实测把 277 条横向下到 7 枚母图时最重的一枚吃了 82 条
    （≈30%），母图的取景缺陷会在那 82 格上集中复制；轮转把复用摊平到 ⌈n/池⌉。
    代价写清楚：映射随成员面重排——补投或判废名单变了要整本台账重生成，不能只追加，
    已投出的条目按台账里登记的 ref_image 原值复核，不靠重算。
    """
    same = [(rel, d) for rel, d in pool if d == size]
    use = same or pool
    if not use:
        raise SystemExit("R4 母图池空（第 %s 位／画幅 %s）" % (idx, size))
    return use[int(idx) % len(use)]
