IDS = sorted(N)


def main():
    with io.open(MEASURE, encoding='utf-8') as fp:
        mea = json.load(fp)
    by = {}
    for row in mea:
        by[row['file'].split('-')[0]] = row
    assert sorted(by) == IDS, (sorted(by), IDS)

    with io.open(NOTES, encoding='utf-8') as fh:
        notes = json.load(fh)
    with io.open(MANIFEST, encoding='utf-8') as _fh:
        man = json.load(_fh)
    items = {it['id']: it for it in man['items']}

    appended = 0
    for k in IDS:
        row = by[k]
        assert row['container']['cabx'] == 1, (k, 'caBX 不在位，不能占格')
        assert row['container']['itxt'] == 0, (k, 'PNG 侧不应出现 iTXt·TC260')
        assert 'C123新串' in row['file'], (k, row['file'])
        old = items[k]['image_file'][0]
        assert 'C118新串' in old, (k, old)
        # 出处头：新文件名＋尺寸＋字节数＋sha12＋容器读数＋被替换的旧格文件名，缺一下一轮就查不到这格是哪批。
        prefix = 'C123新串%s重投人工目视读数：' % k
        assert N[k].startswith(prefix), (k, '读数正文前缀不符')
        body = N[k][len(prefix):]
        note = ('C123新串%s重投（vibe_images/%s，%s，%d字节，sha12=%s，caBX=1、iTXt=0；'
                '替换上一格 %s，旧文件与旧备注都不删）人工目视读数：%s'
                % (k, row['file'], row['dims'], row['bytes'], row['sha256_12'], old, body))
        assert old in note, (k, '读数未写被替换的旧格文件名')

        notes['备注'].setdefault(k, [])
        for prev in notes['备注'][k]:
            assert 'C123新串' not in prev, (k, '本轮读数已打过')
        notes['备注'][k].append(note)

        items[k]['image_file'] = ['vibe_images/' + row['file']]
        items[k]['batch'] = '%s-%sC123新串-v01' % (items[k]['type'], k)
        # 绑定摘要属人工验收动作：本轮不写、也不清别人写的
        assert not items[k].get('image_prompt_sha256'), (k, '已绑定摘要，不该再打表')
        appended += 1

    with io.open(NOTES, 'w', encoding='utf-8') as _fp:
        _fp.write(
            json.dumps(notes, ensure_ascii=False, indent=2) + '\n')
    with io.open(MANIFEST, 'w', encoding='utf-8') as _handle:
        _handle.write(
            json.dumps(man, ensure_ascii=False, indent=2) + '\n')
    print('追加人工读数 %d 条；替换占格 %d 格；image_prompt_sha256 全部留空' % (appended, appended))


if __name__ == '__main__':
    main()
