HARD = re.compile(r'判废')
SOFT = re.compile(r'不作判废|未判废|无判废|不作硬判|判废依据')


def is_clean(text):
    return not [s for s in re.split(r'(?<=[。；])', text) if HARD.search(s) and not SOFT.search(s)]


VAR_RE = re.compile(r'画风细尺度方差全图[0-9.]+、中心[0-9.]+')


def sync_metrics():
    """画风方差两个数一律从本轮测量表取，不许手抄：读数正文里只留句式，数字按 id 回填。"""
    mea_path = os.path.join(HERE, 'batch9d_measure.json')
    rows = json.load(io.open(mea_path, encoding='utf-8'))
    rows = rows['rows'] if isinstance(rows, dict) else rows
    for row in rows:
        text = R[row['id']]
        hit = VAR_RE.findall(text)
        assert len(hit) == 1, (row['id'], hit)
        R[row['id']] = VAR_RE.sub(
            '画风细尺度方差全图%.6f、中心%.6f' % (row['fine_var_full'], row['fine_var_center']),
            text, 1)


def main():
    assert len(R) == 19, len(R)
    sync_metrics()
    for k, v in R.items():
        assert v.endswith('本条只记人工读数，不代签验收。'), k
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write(
        json.dumps(R, ensure_ascii=False, indent=2) + '\n')
    clean = sorted(k for k, v in R.items() if is_clean(v))
    hard = sorted(k for k in R if k not in clean)
    print('可回填 %d 条：%s' % (len(clean), ' '.join(clean)))
    print('判废 %d 条：%s' % (len(hard), ' '.join(hard)))


if __name__ == '__main__':
    main()
